<?php

declare(strict_types=1);

if (getenv('FADEN_DISPOSABLE_TEST') !== 'governed-history-20261027') {
	exit(2);
}
define('OC_CONSOLE', 1);
require '/var/www/html/lib/base.php';
set_exception_handler(static function (\Throwable $error): never {
	fwrite(STDERR, $error::class . ' at ' . basename($error->getFile()) . ':' . $error->getLine() . "\n");
	fwrite(STDERR, json_encode($GLOBALS['checks'] ?? [], JSON_THROW_ON_ERROR) . "\n");
	exit(1);
});

use OCA\FadenstackAgent\History\HistoryService;
use OCA\FadenstackAgent\History\JournalService;
use OCA\FadenstackAgent\Identity\CloudIdentityVerifier;
use OCA\FadenstackAgent\Service\FileService;
use OCA\FadenstackAgent\Service\Problem;
use OCA\FadenstackAgent\Service\ScopePolicy;
use OCP\Files\IRootFolder;
use OCP\IConfig;
use OCP\ISession;
use OCP\IUserManager;
use OCP\IUserSession;
use OCP\Server;
use OCP\Share\IManager;

$checks = [];
$assert = static function (string $name, bool $condition) use (&$checks): void {
	$checks[] = ['case' => $name, 'pass' => $condition];
	if (!$condition) {
		throw new RuntimeException('Failed native boundary check');
	}
};
$denied = static function (string $name, callable $work, int $status) use ($assert): void {
	try {
		$work();
	} catch (Problem $error) {
		$assert($name, $error->status === $status);
		return;
	}
	$assert($name, false);
};
$token = 'synthetic-principal-token-aaaa';
file_put_contents('/tmp/faden-history-mode', 'normal');
$user = Server::get(IUserManager::class)->get('faden-workflow-lab');
Server::get(IUserSession::class)->setUser($user);
$home = Server::get(IRootFolder::class)->getUserFolder($user->getUID());
$folder = $home->newFolder('History boundaries ' . bin2hex(random_bytes(5)));
$file = $folder->newFile('boundary.md', 'Unique synthetic original before history.');
$broker = Server::get(FileService::class);
$cloud = Server::get(CloudIdentityVerifier::class);
$principal = $cloud->verify($token);
$broker->bindCloudPrincipal($principal);
$identity = $broker->pairedHistoryIdentity($principal);
$context = $broker->select($file->getId());
$read = $broker->read($context['id']);
$proposal = $broker->propose($context['id'], 'update', '', 'Unique synthetic generated content.', $read['file']['etag']);
$broker->approve($proposal['id']);
$result = $broker->commit($proposal['id']);
$history = Server::get(HistoryService::class);
$journal = Server::get(JournalService::class);
$preview = $history->prepare($token, $result['actionId'], 'undo');
$session = Server::get(ISession::class);
$saved = serialize($session->get('fadenstack_agent.history'));
$assert('pending history session state contains neither token nor original/generated bytes', !str_contains($saved, $token)
	&& !str_contains($saved, 'Unique synthetic original') && !str_contains($saved, 'Unique synthetic generated'));
$assert('preview preparation holds no native journal claim and creates no execution attempt', count($journal->attempts($identity, $result['actionId'])) === 3
	&& $journal->preview($identity, $result['actionId'])['state'] === 'applied');
$history->approve($token, $preview['id'], $preview['digest']);
file_put_contents('/tmp/faden-history-mode', 'new-device');
$denied('changed device permanently invalidates the observed old approval', fn () => $history->execute($token, $preview['id'], $preview['digest']), 410);
file_put_contents('/tmp/faden-history-mode', 'normal');
$denied('returning to the previous device does not resurrect that consumed approval', fn () => $history->execute($token, $preview['id'], $preview['digest']), 410);
$assert('identity refusal preserves native generated bytes', $file->getContent() === 'Unique synthetic generated content.');

$config = Server::get(IConfig::class);
$oldVersion = $config->getAppValue('fadenstack_agent', 'installed_version', '');
$oldPolicy = $config->getAppValue('fadenstack_agent', ScopePolicy::CONFIG_KEY, '');
$beforeUpgrade = $broker->pairedHistoryIdentity($principal);
$pending = $history->prepare($token, $result['actionId'], 'undo');
$history->approve($token, $pending['id'], $pending['digest']);
try {
	$config->setAppValue('fadenstack_agent', 'installed_version', '0.1.5-fixture');
	$afterUpgrade = $broker->pairedHistoryIdentity($principal);
	$assert('app-version changes retain durable private ownership while changing the attempt binding', $beforeUpgrade->scopeHash === $afterUpgrade->scopeHash && $beforeUpgrade->sessionHash !== $afterUpgrade->sessionHash);
	$assert('existing real broker snapshot remains readable under current rights after version change', $journal->preview($afterUpgrade, $result['actionId'])['snapshot']['inverse']['content'] === 'Unique synthetic original before history.');
	$denied('an old approval does not cross an app-version change', fn () => $history->execute($token, $pending['id'], $pending['digest']), 410);
	$fresh = $history->prepare($token, $result['actionId'], 'undo');
	$assert('a fresh preview can recover the durable action after version change', $fresh['actionId'] === $result['actionId']);
	$history->cancel($token, $fresh['id'], $fresh['digest']);
} finally {
	$config->setAppValue('fadenstack_agent', 'installed_version', $oldVersion);
}
$pending = $history->prepare($token, $result['actionId'], 'undo');
$history->approve($token, $pending['id'], $pending['digest']);
try {
	$config->setAppValue('fadenstack_agent', ScopePolicy::CONFIG_KEY, json_encode(['revision' => 'changed-native-policy',
		'sources' => [['kind' => 'user-files']], 'destinations' => [['kind' => 'user-files']], 'tools' => [...ScopePolicy::FILE_TOOLS, ...ScopePolicy::HISTORY_TOOLS],
		'classificationDefault' => 'standard', 'sourceClasses' => ['standard'], 'movements' => [['source' => 'standard', 'destination' => 'private']]], JSON_THROW_ON_ERROR));
	$afterPolicy = $broker->pairedHistoryIdentity($principal);
	$assert('native-policy publication retains ownership and changes the attempt binding', $identity->scopeHash === $afterPolicy->scopeHash && $identity->sessionHash !== $afterPolicy->sessionHash);
	$denied('an old approval does not cross a native-policy publication', fn () => $history->execute($token, $pending['id'], $pending['digest']), 410);
	$assert('authorized native history remains decryptable under the changed policy', $journal->preview($afterPolicy, $result['actionId'])['state'] === 'applied');
} finally {
	$config->setAppValue('fadenstack_agent', ScopePolicy::CONFIG_KEY, $oldPolicy);
}
$denied('restoring a previous policy cannot resurrect an observed invalid approval', fn () => $history->execute($token, $pending['id'], $pending['digest']), 410);

$pending = [];
for ($i = 0; $i < 10; $i++) {
	$pending[] = $history->prepare($token, $result['actionId'], 'undo');
}
$denied('history preview metadata is capped at ten active preparations', fn () => $history->prepare($token, $result['actionId'], 'undo'), 429);
foreach ($pending as $item) {
	$history->cancel($token, $item['id'], $item['digest']);
}
$assert('cancel removes all unused session previews without touching the action', $session->get('fadenstack_agent.history') === [] && $journal->preview($identity, $result['actionId'])['state'] === 'applied');
$assert('read-only preparation/cancellation does not add native mutation attempts', count($journal->attempts($identity, $result['actionId'])) === 3);

$assert('real private standard-only broker snapshots carry authenticated recovery protection',
	$journal->describe($identity, $result['actionId'])['resource']['recovery'] === 'standard_private_v1');
$policy = ['revision' => 'recovery-protection-fixture', 'sources' => [['kind' => 'user-files']],
	'destinations' => [['kind' => 'user-files']], 'tools' => [...ScopePolicy::FILE_TOOLS, ...ScopePolicy::HISTORY_TOOLS],
	'classificationDefault' => 'standard', 'sourceClasses' => ['standard'], 'destinationAudiences' => ['private', 'shared'],
	'movements' => [['source' => 'standard', 'destination' => 'private'], ['source' => 'standard', 'destination' => 'shared']]];
$shares = Server::get(IManager::class);
$share = null;
try {
	$config->setAppValue('fadenstack_agent', ScopePolicy::CONFIG_KEY, json_encode($policy, JSON_THROW_ON_ERROR));
	$pending = $history->prepare($token, $result['actionId'], 'undo');
	$history->approve($token, $pending['id'], $pending['digest']);
	$share = $shares->newShare();
	$share->setNode($file)->setShareType(\OCP\Share\IShare::TYPE_USER)->setSharedWith('pilot-bob')
		->setSharedBy($user->getUID())->setShareOwner($user->getUID())->setPermissions(\OCP\Constants::PERMISSION_READ);
	$share = $shares->createShare($share);
	$denied('widened audience refuses an approved recovery even when current movement policy allows sharing',
		fn () => $history->execute($token, $pending['id'], $pending['digest']), 403);
	$assert('audience refusal leaves generated bytes and action state intact', $file->getContent() === 'Unique synthetic generated content.'
		&& $journal->describe($broker->pairedHistoryIdentity($principal), $result['actionId'])['state'] === 'applied');
} finally {
	if ($share !== null) {
		$shares->deleteShare($share);
	}
	$config->setAppValue('fadenstack_agent', ScopePolicy::CONFIG_KEY, $oldPolicy);
}

try {
	$policy['classificationDefault'] = 'protected';
	$policy['sourceClasses'] = ['standard', 'protected'];
	$policy['downstreamPolicy'] = 'configured';
	$policy['movements'][] = ['source' => 'protected', 'destination' => 'private'];
	$config->setAppValue('fadenstack_agent', ScopePolicy::CONFIG_KEY, json_encode($policy, JSON_THROW_ON_ERROR));
	$restricted = $folder->newFile('protected-history.md', 'Synthetic protected original.');
	$selected = $broker->select($restricted->getId());
	$read = $broker->read($selected['id']);
	$proposal = $broker->propose($selected['id'], 'update', '', 'Synthetic protected generated.', $read['file']['etag']);
	$broker->approve($proposal['id']);
	$protected = $broker->commit($proposal['id']);
	$assert('broader protected-input policy never certifies a public recovery snapshot',
		!isset($journal->describe($broker->pairedHistoryIdentity($principal), $protected['actionId'])['resource']['recovery']));
} finally {
	$config->setAppValue('fadenstack_agent', ScopePolicy::CONFIG_KEY, $oldPolicy);
}
$denied('later standard classification cannot retroactively certify protected historical bytes',
	fn () => $history->prepare($token, $protected['actionId'], 'undo'), 422);
$items = array_column($history->listing($token), null, 'id');
$assert('uncertified actions remain visible as restoration unavailable without content',
	$items[$protected['actionId']]['eligible'] === 'none' && !isset($items[$protected['actionId']]['content']));
$assert('refused protected recovery preserves current native bytes', $restricted->getContent() === 'Synthetic protected generated.');

echo json_encode(['layer' => 'actual native services, session and paired Files broker', 'checks' => $checks], JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT) . "\n";
